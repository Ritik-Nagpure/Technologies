let i =0 ;

console.log(" -------------- While loop -------------------");

// while loops
// runs till the conditions is true. runs untill condition is false
while(i<10){
    console.log(i);
    i++;
}

console.log(" -------------- Do While loop -------------------");

//Do While loops
// atleast one iterations happens and then condition is tested. runs untill condition is false
do{
    console.log(i);
    i--;
}while(i>0);